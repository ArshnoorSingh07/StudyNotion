// Flatten Swiper's nested CSS before CRA's fixed Tailwind/PostCSS pipeline.
const fs = require('node:fs/promises');
const path = require('node:path');
const postcss = require('postcss');
const nesting = require('tailwindcss/nesting');
async function main() {
  const sources = ['swiper/css', 'swiper/css/free-mode', 'swiper/css/pagination'];
  const styles = await Promise.all(sources.map(async source => {
    const from = require.resolve(source);
    const result = await postcss([nesting()]).process(await fs.readFile(from, 'utf8'), { from, map: false });
    return result.css;
  }));
  const destination = path.join(__dirname, '../src/styles/swiper.css');
  await fs.mkdir(path.dirname(destination), { recursive: true });
  await fs.writeFile(destination, '/* Generated by scripts/prepare-swiper-css.cjs from Swiper (MIT). Do not edit. */\n' + styles.join('\n'));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
